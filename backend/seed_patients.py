def seed_synthetic_patients():
    """Seed exactly 20 synthetic patients idempotently."""
    print(f"Reading current patients from {storage.file_path}...")
    existing_data = storage._read_data()
    existing_patients = existing_data.get("patients", [])
    print(f"Current existing patients count: {len(existing_patients)}")

    # Map existing records by email or mobile to prevent duplicates if rerun
    existing_identifiers = {
        p.get("mobile"): p for p in existing_patients if p.get("mobile")
    }

    added_count = 0
    updated_count = 0
    now = datetime.now(timezone.utc)

    for idx, template in enumerate(SYNTHETIC_PATIENTS):
        mobile = template["mobile"]
        # Stagger creation timestamps across recent days
        created_time = (now - timedelta(days=20 - idx, hours=(idx % 6) + 1)).isoformat()
        
        if mobile in existing_identifiers:
            # Update existing record if rerun to maintain idempotency
            existing_rec = existing_identifiers[mobile]
            rec_id = existing_rec.get("id") or existing_rec.get("uhid")
            update_payload = dict(template)
            storage.update(rec_id, update_payload)
            updated_count += 1
        else:
            # Generate sequential UHID
            current_patients = storage._read_data().get("patients", [])
            new_uhid = storage.generate_next_uhid(current_patients)
            
            payload = dict(template)
            payload["uhid"] = new_uhid
            
            # Use storage create method to ensure atomic file writing
            created = storage.create(payload)
            
            # Fix createdAt timestamp for historical variation
            storage.update(created["id"], {"createdAt": created_time, "updatedAt": created_time})
            added_count += 1
            print(f"  + Added: {created['firstName']} {created['lastName']} ({created['uhid']})")

    final_data = storage._read_data()
    final_count = len(final_data.get("patients", []))
    print(f"\nSeeding complete!")
    print(f"Newly added: {added_count}")
    print(f"Updated (already existed): {updated_count}")
    print(f"Total patient records in JSON: {final_count}")


if __name__ == "__main__":
    seed_synthetic_patients()
